def str2bool(v):
    if isinstance(v, bool): return v
    if v.lower() in ("yes", "true", "t", "y", "1"): return True
    if v.lower() in ("no", "false", "f", "n", "0"): return False
    raise ValueError("Boolean value expected.")


def specificity_score(y_true, y_pred):
    y_true = np.array(y_true)
    y_pred = np.array(y_pred).astype(int)
    TN = ((y_pred == 0) & (y_true == 0)).sum()
    N = (y_true == 0).sum()
    return TN / (N + 1e-8)


# ------------------------------------------------------------------
# Synthetic anomaly generation (Perlin-style smooth random mask)
# ------------------------------------------------------------------
def smooth_random_mask(H, W, device, octaves=4):
    """Generate a smooth, blob-like binary mask by upsampling low-res noise."""
    mask = torch.zeros(1, 1, H, W, device=device)
    for o in range(octaves):
        scale = 2 ** o
        h, w = max(H // (32 // max(scale, 1)), 2), max(W // (32 // max(scale, 1)), 2)
        noise = torch.rand(1, 1, h, w, device=device)
        noise = F.interpolate(noise, size=(H, W), mode="bilinear", align_corners=False)
        mask += noise
    mask = mask / octaves
    thresh = torch.quantile(mask.flatten(), 0.80)  # top ~20% of area becomes the anomaly
    binary_mask = (mask > thresh).float()
    return binary_mask  # (1, 1, H, W)


def generate_synthetic_anomaly(x, device):
    """
    x: (B, C, H, W) batch of normal images.
    Returns (corrupted_x, gt_mask) where gt_mask: (B, 1, H, W) in {0, 1}.
    Anomaly texture is sourced from a random crop of another image in
    the same batch (see module docstring for why: no external texture
    dataset is available in this environment).
    """
    B, C, H, W = x.shape
    corrupted = x.clone()
    masks = []
    perm = torch.randperm(B)
    for i in range(B):
        mask = smooth_random_mask(H, W, device)  # (1,1,H,W)
        src = x[perm[i]:perm[i] + 1]
        jitter = (torch.rand(1, C, 1, 1, device=device) - 0.5) * 0.6  # +/- intensity shift
        texture = torch.clamp(src + jitter, 0.0, 1.0)
        beta = 0.7  # blend strength, matching DRAEM's default range
        corrupted[i:i + 1] = corrupted[i:i + 1] * (1 - mask) + \
            (beta * texture + (1 - beta) * corrupted[i:i + 1]) * mask
        masks.append(mask)
    gt_mask = torch.cat(masks, dim=0)
    return corrupted, gt_mask


# ------------------------------------------------------------------
# Reconstructive sub-network (simple encoder-decoder)
# ------------------------------------------------------------------
class ReconstructiveNet(nn.Module):
    def __init__(self, in_ch=3):
        super().__init__()
        self.enc = nn.Sequential(
            nn.Conv2d(in_ch, 32, 4, 2, 1), nn.BatchNorm2d(32), nn.ReLU(True),
            nn.Conv2d(32, 64, 4, 2, 1), nn.BatchNorm2d(64), nn.ReLU(True),
            nn.Conv2d(64, 128, 4, 2, 1), nn.BatchNorm2d(128), nn.ReLU(True),
            nn.Conv2d(128, 256, 4, 2, 1), nn.BatchNorm2d(256), nn.ReLU(True),
        )
        self.dec = nn.Sequential(
            nn.ConvTranspose2d(256, 128, 4, 2, 1), nn.BatchNorm2d(128), nn.ReLU(True),
            nn.ConvTranspose2d(128, 64, 4, 2, 1), nn.BatchNorm2d(64), nn.ReLU(True),
            nn.ConvTranspose2d(64, 32, 4, 2, 1), nn.BatchNorm2d(32), nn.ReLU(True),
            nn.ConvTranspose2d(32, in_ch, 4, 2, 1), nn.Sigmoid(),
        )

    def forward(self, x):
        return self.dec(self.enc(x))


# ------------------------------------------------------------------
# Discriminative sub-network (segmentation on [input || reconstruction])
# ------------------------------------------------------------------
class DiscriminativeNet(nn.Module):
    def __init__(self, in_ch=6):
        super().__init__()
        self.enc1 = nn.Sequential(nn.Conv2d(in_ch, 32, 3, 1, 1), nn.BatchNorm2d(32), nn.ReLU(True))
        self.enc2 = nn.Sequential(nn.Conv2d(32, 64, 3, 2, 1), nn.BatchNorm2d(64), nn.ReLU(True))
        self.enc3 = nn.Sequential(nn.Conv2d(64, 128, 3, 2, 1), nn.BatchNorm2d(128), nn.ReLU(True))
        self.dec2 = nn.Sequential(nn.ConvTranspose2d(128, 64, 4, 2, 1), nn.BatchNorm2d(64), nn.ReLU(True))
        self.dec1 = nn.Sequential(nn.ConvTranspose2d(64, 32, 4, 2, 1), nn.BatchNorm2d(32), nn.ReLU(True))
        self.out = nn.Conv2d(32, 1, 3, 1, 1)

    def forward(self, x):
        e1 = self.enc1(x)
        e2 = self.enc2(e1)
        e3 = self.enc3(e2)
        d2 = self.dec2(e3)
        d1 = self.dec1(d2)
        return self.out(d1)  # logits, (B, 1, H, W)


def run_single_seed(args, seed):
    args.seed = seed
    random.seed(seed)
    torch.manual_seed(seed)
    np.random.seed(seed)
    cudnn.deterministic = True

    save_name = f"baseline_draem_lungct_seed{seed}"
    save_path = os.path.join(args.save_dir, save_name)
    os.makedirs(save_path, exist_ok=True)
    logger = get_logger(save_name, save_path, "INFO")
    logger.warning(f"[LungCT Baseline-DRAEM] Seed={seed} GPU={args.gpu}")

    ds_train = AD_Dataset_WithVal(
        name=args.dataset, data_dir=args.data_dir,
        img_size=args.img_size, crop_size=args.img_size,
        val_fraction=0.2, seed=seed, train=True,
    )
    train_dset = ds_train.get_train_dset()
    val_dset = ds_train.get_val_dset()
    eval_dset = AD_Dataset_WithVal(
        name=args.dataset, data_dir=args.data_dir,
        img_size=args.img_size, train=False,
    ).get_eval_dset()

    tl = np.array(train_dset.targets)
    el = np.array(eval_dset.targets)
    print(f"Train normal: {Counter(tl)[0]} | Val: {len(val_dset)} | "
          f"Test Normal: {Counter(el)[0]} Abnormal: {Counter(el)[1]}")

    generator = torch.Generator()
    generator.manual_seed(seed)

    train_loader = get_data_loader(
        train_dset, args.batch_size, data_sampler=args.train_sampler,
        num_iters=args.num_train_iter, num_workers=args.num_workers,
        distributed=False, generator=generator,
    )
    val_loader = get_data_loader(val_dset, args.eval_batch_size,
                                  num_workers=args.num_workers, drop_last=False)
    eval_loader = get_data_loader(eval_dset, args.eval_batch_size,
                                   num_workers=args.num_workers, drop_last=False)

    device = torch.device(f"cuda:{args.gpu}" if torch.cuda.is_available() else "cpu")
    recon_net = ReconstructiveNet(in_ch=3).to(device)
    disc_net = DiscriminativeNet(in_ch=6).to(device)
    logger.info(f"Reconstructive params: {count_parameters(recon_net):,} | "
                f"Discriminative params: {count_parameters(disc_net):,}")

    params = list(recon_net.parameters()) + list(disc_net.parameters())
    optimizer = torch.optim.AdamW(params, lr=args.lr, weight_decay=args.weight_decay)

    recon_net.train(); disc_net.train()
    it = 0
    data_iter = iter(train_loader)
    while it < args.num_train_iter:
        try:
            _, x, _, _, _ = next(data_iter)
        except StopIteration:
            data_iter = iter(train_loader)
            _, x, _, _, _ = next(data_iter)
        x = x.to(device)

        corrupted, gt_mask = generate_synthetic_anomaly(x, device)
        recon = recon_net(corrupted)

        recon_loss = F.l1_loss(recon, x) + F.mse_loss(recon, x)

        disc_input = torch.cat([corrupted, recon], dim=1)
        pred_logits = disc_net(disc_input)
        seg_loss = F.binary_cross_entropy_with_logits(pred_logits, gt_mask)

        total_loss = recon_loss + args.lambda_seg * seg_loss

        optimizer.zero_grad()
        total_loss.backward()
        optimizer.step()

        if (it + 1) % 100 == 0:
            logger.info(f"iter {it+1}/{args.num_train_iter}  "
                        f"recon_loss={recon_loss.item():.4f}  seg_loss={seg_loss.item():.4f}")
        it += 1

    # ---- Threshold: 95th percentile of VALIDATION-NORMAL discriminative scores ----
    recon_net.eval(); disc_net.eval()

    def score_batch(x):
        with torch.no_grad():
            recon = recon_net(x)
            disc_input = torch.cat([x, recon], dim=1)
            logits = disc_net(disc_input)
            amap = torch.sigmoid(logits).squeeze(1)  # (B, H, W)
        return amap.cpu().numpy()

    def reduce_map(amap, reduction="max"):
        flat = amap.reshape(amap.shape[0], -1)
        return flat.mean(1) if reduction == "mean" else flat.max(1)

    with torch.no_grad():
        val_scores = []
        for _, x, _, _, _ in val_loader:
            x = x.to(device)
            amap = score_batch(x)
            val_scores.extend(reduce_map(amap, args.amap_reduction).tolist())
        val_scores = np.array(val_scores)
        thresh = float(np.percentile(val_scores, 95.0))
        print(f"[Threshold] From val-normal 95th-pct ({len(val_scores)} images): {thresh:.4f}")

        y_true, y_prob = [], []
        for _, x, _, y, _ in eval_loader:
            x = x.to(device)
            amap = score_batch(x)
            score = reduce_map(amap, args.amap_reduction)
            y_true.extend(y.tolist())
            y_prob.extend(score.tolist())

    y_true = np.array(y_true)
    y_prob = np.array(y_prob)
    y_pred = (y_prob >= thresh).astype(int)

    acc = accuracy_score(y_true, y_pred)
    f1 = f1_score(y_true, y_pred, zero_division=0)
    recall = recall_score(y_true, y_pred, zero_division=0)
    specificity = specificity_score(y_true, y_pred)
    precision = float(np.sum((y_pred == 1) & (y_true == 1)) / (np.sum(y_pred == 1) + 1e-8))
    AUC = roc_auc_score(y_true, y_prob)
    AP = average_precision_score(y_true, y_prob)

    cm = confusion_matrix(y_true, y_pred)
    print(f"\n===== CONFUSION MATRIX (Baseline DRAEM, LungCT, seed={seed}) =====")
    print(f"TN={cm[0,0]}  FP={cm[0,1]}")
    print(f"FN={cm[1,0]}  TP={cm[1,1]}")
    print(f"Accuracy={acc:.4f}  Precision={precision:.4f}  Recall={recall:.4f}")
    print(f"F1={f1:.4f}  Specificity={specificity:.4f}  AUROC={AUC:.4f}  AP={AP:.4f}\n")
    print(classification_report(y_true, y_pred, target_names=["NORMAL", "ABNORMAL"], digits=4))

    os.makedirs("results/baselines", exist_ok=True)
    result = {
        "Baseline": "DRAEM", "Dataset": "LungCT", "Seed": seed,
        "AUROC": AUC, "AP": AP, "Accuracy": acc,
        "Precision": precision, "Recall": recall, "F1": f1, "Specificity": specificity,
    }
    pd.DataFrame([result]).to_csv(
        f"results/baselines/{save_name}.csv", index=False, float_format="%.4f"
    )
    print(f"Saved: results/baselines/{save_name}.csv")
    return result


def main():
    import argparse
    parser = argparse.ArgumentParser(description="LungCT Baseline: DRAEM")
    parser.add_argument("--save_dir", type=str, default="./saved_models")
    parser.add_argument("--num_train_iter", type=int, default=1000)
    parser.add_argument("--batch_size", type=int, default=16)
    parser.add_argument("--eval_batch_size", type=int, default=32)
    parser.add_argument("--lr", type=float, default=1e-4)
    parser.add_argument("--weight_decay", type=float, default=1e-4)
    parser.add_argument("--lambda_seg", type=float, default=1.0)
    parser.add_argument("--data_dir", type=str, default=DATASET_DIR)
    parser.add_argument("--dataset", type=str, default="lungct")
    parser.add_argument("--train_sampler", type=str, default="RandomSampler")
    parser.add_argument("--img_size", type=int, default=256)
    parser.add_argument("--num_workers", type=int, default=4)
    parser.add_argument("--amap_reduction", type=str, default="max")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--seeds", type=int, nargs="+", default=None)
    parser.add_argument("--gpu", type=str, default="0")
    parser.add_argument("--c", type=str, default="")

    args = parser.parse_args()
    over_write_args_from_file(args, args.c)

    seeds = args.seeds if args.seeds else [args.seed]
    all_results = []
    for seed in seeds:
        all_results.append(run_single_seed(args, seed))

    if len(all_results) > 1:
        keys = ["AUROC", "AP", "Accuracy", "Precision", "Recall", "F1", "Specificity"]
        print(f"\n{'='*60}\n  LungCT Baseline-DRAEM — 3-Seed Summary\n{'='*60}")
        for k in keys:
            vals = [r[k] for r in all_results]
            print(f"  {k:12s}: {np.mean(vals):.4f} +/- {np.std(vals):.4f}")


if __name__ == "__main__":
    main()