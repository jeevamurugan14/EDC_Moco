"""
runners_edc_ssl/edc_ssl_lungct_baseline_draem.py
Baseline B2-5: DRAEM (Discriminatively trained Reconstruction Embedding
for surface Anomaly detection).
Dataset: LungCT

Two sub-networks are trained jointly, entirely on normal training
images, with NO abnormal labels used anywhere:
  1. Reconstructive sub-network (an autoencoder): normal images are
     corrupted with a synthetically generated anomaly (a smooth random
     mask, blended with a colour/intensity-shifted patch sourced from
     another image in the same batch) and the network is trained to
     reconstruct the ORIGINAL, uncorrupted image.
  2. Discriminative sub-network: takes the concatenation of the
     corrupted input and its reconstruction, and is trained to predict
     a per-pixel binary mask of where the synthetic anomaly was placed
     (a segmentation task with fully known ground truth, since the
     synthetic mask is generated by us).
At inference, the discriminative network's output map on a REAL test
image (paired with its own reconstruction) is used directly as the
anomaly map; no synthetic corruption is applied at test time.

NOTE ON SIMPLIFICATION: the original DRAEM paper sources the blended
anomaly texture from an external texture dataset (DTD - Describable
Textures Dataset). That dataset is not available in this environment;
here, the anomaly texture is instead sourced from a randomly chosen,
randomly cropped patch of ANOTHER image already in the same training
batch, colour/intensity-jittered. This is a documented deviation from
the original paper, used purely to avoid an external dependency; the
core two-network discriminative-reconstruction mechanism is otherwise
implemented as described in the original paper.

Same data splits, same val-based threshold, same metrics as the other
baselines, for a fair same-protocol comparison.
To adapt to BUSI / APTOS: copy this file, change the DATASET_DIR
import and --dataset default, exactly as with the other baselines.
"""

